/* global process, console */
// Writes Studio's colour palette from the design tokens (the deriva-studio identity) into
// src/theme/tokens.css, between the design-tokens:start and design-tokens:end markers.
// Usage: node scripts/sync-design-tokens.mjs <path/to/deriva-studio/tokens.json> <path/to/anywidgets/tokens.json>
// The second file gives the cluster colours (--cluster-1..8): the anywidgets' validated data palette.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = process.argv[2];
const widgets = process.argv[3];
if (!source || !widgets) {
  console.error("usage: node scripts/sync-design-tokens.mjs <path/to/deriva-studio/tokens.json> <path/to/anywidgets/tokens.json>");
  process.exit(2);
}
const target = path.join(here, "..", "src", "theme", "tokens.css");

// Studio variable -> design token (the deriva-studio identity)
const MAP = {
  bg: "background", bg2: "surface", bg3: "teal-panel", bg4: "selected", line: "border",
  text: "foreground", muted: "muted-foreground", faint: "muted-foreground",
  accent: "link", "on-accent": "primary-foreground", primary: "primary", "primary-foreground": "primary-foreground", ring: "ring",
  "brand-ring1": "mark-inner", "brand-ring2": "mark-second", "brand-ring3": "mark-outer", "brand-core": "mark-core",
  ok: "status-ok", warn: "status-warn", bad: "status-error", "radius-box": "radius-box", "radius-control": "radius-control",
  biz: "data-1", app: "data-2", tech: "data-3", inter: "data-4", code: "muted",
};
const SOFT = { dark: "29", light: "1f" }; // accent-soft: the link colour at 16% (dark) or 12% (light)

const tokens = JSON.parse(readFileSync(source, "utf8"));
const widgetTokens = JSON.parse(readFileSync(widgets, "utf8"));
function block(selector, mode) {
  const t = tokens[mode];
  const lines = Object.entries(MAP).map(([name, token]) => {
    if (!(token in t)) throw new Error(`design token "${token}" missing in ${mode}`);
    return `  --${name}: ${t[token]};`;
  });
  for (let n = 1; n <= 8; n++) lines.push(`  --cluster-${n}: ${widgetTokens[mode][`data-${n}`]};`);
  lines.push(`  --accent-soft: ${t.link}${SOFT[mode]};`, `  color-scheme: ${mode};`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

const generated = `/* design-tokens:start (generated by scripts/sync-design-tokens.mjs from ${path.basename(path.dirname(source))}/tokens.json; do not edit) */
${block(':root,\n:root[data-theme="dark"]', "dark")}

${block(':root[data-theme="light"]', "light")}
/* design-tokens:end */`;

const css = readFileSync(target, "utf8");
const next = css.replace(/\/\* design-tokens:start[\s\S]*?\/\* design-tokens:end \*\//, generated);
if (next === css && !css.includes("design-tokens:start")) throw new Error("markers not found in tokens.css");
writeFileSync(target, next);
console.log(`palette written to ${path.relative(process.cwd(), target)}`);
